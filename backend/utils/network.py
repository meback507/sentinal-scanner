import os
import socket
import urllib.request
import json
import logging

logger = logging.getLogger("sentinel.network")


def get_lan_ip() -> str:
    """Detects primary local LAN IP address via outbound routing probe."""
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        try:
            return socket.gethostbyname(socket.gethostname())
        except Exception:
            return "127.0.0.1"

import time

_CACHED_PUBLIC_IP = None
_LAST_PUBLIC_IP_CHECK = 0.0

def get_public_ip() -> str:
    """
    Detects the public / external IP of the server.
    Checks environment overrides (SENTINEL_HOST, PUBLIC_IP, SERVER_IP),
    then queries reliable IP lookup endpoints with quick timeouts.
    Caches results for 300 seconds to prevent blocking requests.
    """
    global _CACHED_PUBLIC_IP, _LAST_PUBLIC_IP_CHECK
    env_ip = os.environ.get("SENTINEL_HOST") or os.environ.get("PUBLIC_IP") or os.environ.get("SERVER_IP")
    if env_ip:
        return env_ip.strip()

    now = time.time()
    if _CACHED_PUBLIC_IP and (now - _LAST_PUBLIC_IP_CHECK < 300):
        return _CACHED_PUBLIC_IP

    lookup_urls = [
        "https://api.ipify.org",
        "https://ifconfig.me/ip",
        "https://icanhazip.com"
    ]
    for url in lookup_urls:
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "curl/7.68.0"})
            with urllib.request.urlopen(req, timeout=1.0) as resp:
                ip = resp.read().decode("utf-8").strip()
                if ip and len(ip) <= 45:
                    _CACHED_PUBLIC_IP = ip
                    _LAST_PUBLIC_IP_CHECK = now
                    return ip
        except Exception:
            continue

    lan_ip = get_lan_ip()
    _CACHED_PUBLIC_IP = lan_ip
    _LAST_PUBLIC_IP_CHECK = now
    return lan_ip


def get_server_network_info(client_host: str = None) -> dict:
    """
    Returns complete network information for the Sentinel AppSec platform:
    - port
    - lan_ip
    - public_ip
    - best_host
    - server_url
    - client_accessible_url (derived from incoming Host header if present)
    - vscode_settings
    - vscode_uri
    """
    port = int(os.environ.get("PORT", "8000"))
    lan_ip = get_lan_ip()
    public_ip = get_public_ip()

    custom_host = os.environ.get("SENTINEL_HOST")
    if custom_host:
        best_host = custom_host.strip()
    elif lan_ip and lan_ip != "127.0.0.1" and not lan_ip.startswith("172."):
        best_host = lan_ip
    elif public_ip and public_ip != "127.0.0.1" and not public_ip.startswith("172."):
        best_host = public_ip
    else:
        best_host = "127.0.0.1"

    safe_lan_ip = "127.0.0.1" if (not lan_ip or lan_ip.startswith("172.")) else lan_ip
    server_url = f"http://{best_host}:{port}"

    client_accessible_url = server_url
    if client_host:
        clean_client_host = client_host.strip()
        if not clean_client_host.startswith("http://") and not clean_client_host.startswith("https://"):
            client_accessible_url = f"http://{clean_client_host}"
        else:
            client_accessible_url = clean_client_host

    return {
        "port": port,
        "lan_ip": safe_lan_ip,
        "public_ip": public_ip,
        "best_host": best_host,
        "server_url": server_url,
        "client_accessible_url": client_accessible_url,
        "vscode_settings": {
            "sentinel.serverUrl": client_accessible_url
        },
        "vscode_uri": f"vscode://sentinel-security.sentinel-appsec-ide/connect?serverUrl={client_accessible_url}"
    }


def auto_write_workspace_config() -> dict:
    """
    Automatically writes / updates .sentinel/config.json in the repository workspace
    so that the IDE extension can discover the hosted server IP automatically.
    Also optionally updates .vscode/settings.json if .vscode directory exists.
    """
    try:
        base_dir = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        sentinel_dir = os.path.join(base_dir, ".sentinel")
        os.makedirs(sentinel_dir, exist_ok=True)

        info = get_server_network_info()
        config_path = os.path.join(sentinel_dir, "config.json")

        config_data = {
            "serverUrl": info["server_url"],
            "lanUrl": f"http://{info['lan_ip']}:{info['port']}",
            "publicUrl": info["server_url"],
            "host": info["best_host"],
            "port": info["port"],
            "autoConfigured": True,
            "description": "Auto-generated by Sentinel AppSec Server. Used by Sentinel IDE extension for automatic server discovery."
        }

        with open(config_path, "w", encoding="utf-8") as f:
            json.dump(config_data, f, indent=2)

        # Also update or create .vscode/settings.json in the workspace root if appropriate
        vscode_dir = os.path.join(base_dir, ".vscode")
        try:
            os.makedirs(vscode_dir, exist_ok=True)
            settings_path = os.path.join(vscode_dir, "settings.json")
            existing_settings = {}
            if os.path.exists(settings_path):
                with open(settings_path, "r", encoding="utf-8") as sf:
                    existing_settings = json.load(sf)
            existing_settings["sentinel.serverUrl"] = info["server_url"]
            with open(settings_path, "w", encoding="utf-8") as sf:
                json.dump(existing_settings, sf, indent=2)
        except Exception:
            pass

        return config_data
    except Exception as e:
        logger.warning(f"Could not auto-write workspace config: {e}")
        return None
